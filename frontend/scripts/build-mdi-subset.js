const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const sourceRoots = ['components', 'pages', 'layouts', 'plugins', 'store', 'utils'];
const iconNames = new Set();

function collectIcons(dir) {
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const file = path.join(dir, entry.name);
		if (entry.isDirectory()) collectIcons(file);
		else if (/\.(vue|ts|js)$/.test(entry.name)) {
			const source = fs.readFileSync(file, 'utf8');
			for (const match of source.matchAll(/mdi-[a-z0-9-]+/g)) {
				iconNames.add(match[0].slice(4));
			}
		}
	}
}

for (const sourceRoot of sourceRoots) {
	const dir = path.join(root, sourceRoot);
	if (fs.existsSync(dir)) collectIcons(dir);
}

const vuetifyPreset = fs.readFileSync(
	path.join(root, 'node_modules/vuetify/lib/services/icons/presets/mdi.js'),
	'utf8'
);
for (const match of vuetifyPreset.matchAll(/mdi-[a-z0-9-]+/g)) {
	iconNames.add(match[0].slice(4));
}

const mdiCss = fs.readFileSync(
	path.join(root, 'node_modules/@mdi/font/css/materialdesignicons.css'),
	'utf8'
);
const codepoints = new Map();
for (const match of mdiCss.matchAll(/\.mdi-([a-z0-9-]+)::before \{\s+content: "\\([A-F0-9]+)";/g)) {
	codepoints.set(match[1], match[2]);
}

const icons = Array.from(iconNames).sort();
const missing = icons.filter(icon => !codepoints.has(icon));
if (missing.length) {
	throw new Error(`Icons missing from @mdi/font: ${missing.join(', ')}`);
}

const mappings = icons
	.map(icon => `.mdi-${icon}::before { content: "\\${codepoints.get(icon)}"; }`)
	.join('\n');
const scss = `/* Generated by npm run build:icons. Do not edit manually. */
@font-face {
\tfont-family: "Material Design Icons";
\tsrc: url("./fonts/materialdesignicons-subset.woff2") format("woff2");
\tfont-weight: normal;
\tfont-style: normal;
\tfont-display: block;
}

.mdi::before,
.mdi-set {
\tdisplay: inline-block;
\tfont: normal normal normal 24px/1 "Material Design Icons";
\tfont-size: inherit;
\ttext-rendering: auto;
\tline-height: inherit;
\t-webkit-font-smoothing: antialiased;
\t-moz-osx-font-smoothing: grayscale;
}

${mappings}
`;

fs.writeFileSync(path.join(root, 'assets/mdi.scss'), scss);
fs.mkdirSync(path.join(root, 'assets/fonts'), { recursive: true });

const unicodes = icons.map(icon => `U+${codepoints.get(icon)}`).join(',');
const subset = spawnSync('pyftsubset', [
	path.join(root, 'node_modules/@mdi/font/fonts/materialdesignicons-webfont.woff2'),
	`--output-file=${path.join(root, 'assets/fonts/materialdesignicons-subset.woff2')}`,
	`--unicodes=${unicodes}`,
	'--flavor=woff2',
	'--no-hinting'
], { stdio: 'inherit' });

if (subset.error) throw subset.error;
if (subset.status !== 0) process.exit(subset.status || 1);

console.log(`Generated MDI subset with ${icons.length} icons.`);
